#!/usr/bin/env bash
# Starts, stops and inspects the performance-test system under test (SUT).
#
#   perf-stack.sh init <public-ip-or-hostname> [--force]   write .env.perf with fresh random secrets
#   perf-stack.sh up                                       start the stack (PERF_MONITORING=off: without monitoring)
#   perf-stack.sh status                                   container state
#   perf-stack.sh stats                                    one-shot CPU / memory per container
#   perf-stack.sh logs [service...]                        follow logs
#   perf-stack.sh check                                    validate the merged compose files, start nothing
#   perf-stack.sh config                                   print the merged compose files
#   perf-stack.sh down [-v]                                stop; -v also deletes the volumes (a clean slate)
#
# The files are layered exactly like CI and local development (infrastructure, apps, apps-local), plus
# docker-compose-perf.yaml last, with the CI env files first and .env.perf on top: a later --env-file
# wins. See tools/docker/perf/README.md.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOCKER_DIR="$(cd "$HERE/.." && pwd)"
ENV_FILE="${PERF_ENV_FILE:-$HERE/.env.perf}"

die() { echo "perf-stack: $*" >&2; exit 1; }

compose() {
  docker compose -p processpuzzle --project-directory "$DOCKER_DIR" \
    --env-file "$DOCKER_DIR/env/infrastructure/.env.ci" \
    --env-file "$DOCKER_DIR/env/testbed/.env.ci" \
    --env-file "$ENV_FILE" \
    -f "$DOCKER_DIR/docker-compose-infrastructure.yaml" \
    -f "$DOCKER_DIR/docker-compose-apps.yaml" \
    -f "$DOCKER_DIR/docker-compose-apps-local.yaml" \
    -f "$HERE/docker-compose-perf.yaml" \
    "$@"
}

require_env() {
  [[ -f "$ENV_FILE" ]] || die "$ENV_FILE not found. Run: $0 init <public-ip-or-hostname>"
}

profiles() {
  if [[ "${PERF_MONITORING:-on}" == "off" ]]; then echo ""; else echo "monitoring"; fi
}

init() {
  local host="${1:-}"
  [[ -n "$host" ]] || die "usage: $0 init <public-ip-or-hostname> [--force]"
  if [[ -e "$ENV_FILE" && "${2:-}" != "--force" ]]; then
    die "$ENV_FILE already exists; pass --force to replace it (this changes every secret)"
  fi
  command -v openssl >/dev/null || die "openssl is required to generate secrets"
  rnd() { openssl rand -hex 16; }
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by perf-stack.sh init on $(date -u +%Y-%m-%dT%H:%M:%SZ). Holds secrets: never commit it.
# Layered over tools/docker/env/{infrastructure,testbed}/.env.ci; a value here wins.

# ── Where the SUT is reached from outside ───────────────────────────────────────────────────────
PERF_PUBLIC_HOST=${host}
# What the browser-facing URLs name. Tokens carry KC_HOSTNAME as issuer, and presigned MinIO URLs
# carry MINIO_PUBLIC_ENDPOINT, so a load generator on another host needs both to be reachable.
KC_HOSTNAME=http://${host}:7070
PROCESSPUZZLE_SECURITY_ISSUER_BASE_URL=http://${host}:7070
MINIO_PUBLIC_ENDPOINT=http://${host}:7000
APP_CORS_ALLOWED_ORIGINS=http://${host}:9090

# ── Images ──────────────────────────────────────────────────────────────────────────────────────
# Pin a promoted sha-<commit> to test exactly what stage runs.
PP_IMAGE_TAG=latest

# ── Secrets, fresh per host ─────────────────────────────────────────────────────────────────────
POSTGRES_PASSWORD=$(rnd)
PROCESSPUZZLE_DB_PASSWORD=$(rnd)
KEYCLOAK_ADMIN_PASSWORD=$(rnd)
PLATFORM_ADMIN_CLIENT_SECRET=$(rnd)
MINIO_ROOT_PASSWORD=$(rnd)
MINIO_SERVICE_PASSWORD=$(rnd)
VISION_SERVICE_TOKEN=$(rnd)
PERF_GRAFANA_ADMIN_PASSWORD=$(rnd)

# ── Published ports (host:container) ────────────────────────────────────────────────────────────
# 0.0.0.0 only where the load generator must reach the SUT: restrict these four in the cloud
# firewall to the generator's IP and yours. Everything else stays on loopback.
PP_TESTBED_FRONTEND_PUBLISH=0.0.0.0:9090:80
PP_KEYCLOAK_PUBLISH=0.0.0.0:7070:8080
PP_MINIO_API_PUBLISH=0.0.0.0:7000:9000
PP_TESTBED_BACKEND_PUBLISH=127.0.0.1:8080:8080
PP_POSTGRES_PUBLISH=127.0.0.1:5432:5432
PP_MINIO_CONSOLE_PUBLISH=127.0.0.1:7001:9001
PP_PGWEB_PUBLISH=127.0.0.1:8082:8081
PP_JSON_SERVER_PUBLISH=127.0.0.1:3000:3000
PP_VISION_SERVER_PUBLISH=127.0.0.1:8000:8000
PP_MAILPIT_SMTP_PUBLISH=127.0.0.1:1025:1025
PP_MAILPIT_UI_PUBLISH=127.0.0.1:8025:8025
# Monitoring: loopback. Reach Grafana with  ssh -L 3001:127.0.0.1:3001 <host>  and let k6 push to
# Prometheus through  ssh -L 9099:127.0.0.1:9099 <host>, or publish 9099 and firewall it.
PERF_GRAFANA_PUBLISH=127.0.0.1:3001:3000
PERF_PROMETHEUS_PUBLISH=127.0.0.1:9099:9090

# ── Memory caps ─────────────────────────────────────────────────────────────────────────────────
# The defaults are the stage values (a 3.8 GiB host), so an untouched run reproduces stage. For a
# scaled run on a bigger VPS, uncomment and raise; JVM heaps follow their cap automatically.
# PERF_BACKEND_MEM_LIMIT=3g
# PERF_POSTGRES_MEM_LIMIT=3g
# PERF_PG_SHARED_BUFFERS=1GB
# PERF_KEYCLOAK_MEM_LIMIT=1536m
# PERF_MINIO_MEM_LIMIT=1g
# PERF_FRONTEND_MEM_LIMIT=256m

# ── Behaviour ───────────────────────────────────────────────────────────────────────────────────
# true = the production setting: every tenant API call needs a bearer token. Stage runs false today.
# PERF_REQUIRE_AUTHENTICATION=true
EOF
  echo "wrote $ENV_FILE (mode 600). Next: $0 check && $0 up"
}

cmd="${1:-}"
[[ -n "$cmd" ]] || { sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; exit 1; }
shift || true

case "$cmd" in
  init)   init "$@" ;;
  up)     require_env; COMPOSE_PROFILES="$(profiles)" compose up -d --wait "$@" ;;
  down)   require_env; compose --profile '*' down "$@" ;;
  status) require_env; COMPOSE_PROFILES="$(profiles)" compose ps "$@" ;;
  logs)   require_env; COMPOSE_PROFILES="$(profiles)" compose logs -f --tail 100 "$@" ;;
  config) require_env; COMPOSE_PROFILES="$(profiles)" compose config "$@" ;;
  check)  require_env; COMPOSE_PROFILES="$(profiles)" compose config --quiet && echo "compose files are valid" ;;
  stats)  docker stats --no-stream --format 'table {{.Name}}\t{{.CPUPerc}}\t{{.MemUsage}}\t{{.MemPerc}}\t{{.BlockIO}}' ;;
  *)      die "unknown command '$cmd' (init, up, down, status, logs, config, check, stats)" ;;
esac
