/** What kind of object a conversation is about. Only entity instances for now. */
export type ChatSubjectType = 'ENTITY';

export type ConversationStatus = 'OPEN' | 'CLOSED' | 'ARCHIVED';

export type MessageKind = 'TEXT';

/** What the caller may do in a conversation right now. */
export interface ConversationPermissions {
  canWrite: boolean;
}

/** One chat on one subject, as `base-chat-api.yaml` describes it. */
export interface Conversation {
  id: string;
  definitionKey: string;
  subjectType: ChatSubjectType;
  subjectDefinition: string;
  subjectId: string;
  title?: string | null;
  status: ConversationStatus;
  /** The `seq` of the newest message; 0 for an empty conversation. */
  lastSeq: number;
  createdBy?: string | null;
  createdAt?: string;
  permissions: ConversationPermissions;
  /** Whether the caller follows it: it is on the live stream and counts unread. */
  following: boolean;
  /** The caller's read marker; absent when they do not follow it. */
  lastReadSeq?: number | null;
  /** The server's count when it answered — stale as soon as a message arrives; use {@link unreadOf}. */
  unread: number;
}

export interface ChatMessage {
  /** Number within its conversation, without gaps. */
  seq: number;
  /** Generated by the client, once per message; what makes a post idempotent. */
  clientMessageId: string;
  authorId: string;
  authorName?: string | null;
  kind: MessageKind;
  body: string;
  createdAt: string;
}

export interface ReadState {
  conversationId: string;
  lastReadSeq: number;
  lastSeq: number;
  unread: number;
}

/** The answer to a post: `created` is false when it was the replay of an earlier one. */
export interface PostedMessage {
  message: ChatMessage;
  created: boolean;
}

/** The thing a chat is about, as the panel is told it. */
export interface ChatSubjectRef {
  subjectType: ChatSubjectType;
  subjectId: string;
}

/** Messages newer than the caller's marker; 0 when they do not follow the conversation. */
export function unreadOf(conversation: Conversation): number {
  return conversation.following ? Math.max(0, conversation.lastSeq - (conversation.lastReadSeq ?? 0)) : 0;
}

/** Why a call failed, in terms a panel can say to the user. */
export type ChatFailureKind = 'forbidden' | 'not-found' | 'conflict' | 'invalid' | 'unavailable';

/** A number in [0, 1) from the platform's random source — not for secrets, but there is no reason to use a worse one. */
export function randomFraction(): number {
  return (globalThis.crypto.getRandomValues(new Uint32Array(1))[0] ?? 0) / 2 ** 32;
}

/**
 * A fresh id for a message the client is about to send. `randomUUID` exists only in secure contexts — not on a
 * development server reached over plain HTTP — where `getRandomValues` still does, so the id is built from that.
 */
export function newClientMessageId(): string {
  if (typeof globalThis.crypto.randomUUID === 'function') return globalThis.crypto.randomUUID();
  const bytes = globalThis.crypto.getRandomValues(new Uint8Array(16));
  bytes[6] = ((bytes[6] ?? 0) & 0x0f) | 0x40; // version 4
  bytes[8] = ((bytes[8] ?? 0) & 0x3f) | 0x80; // variant 10
  const hex = [...bytes].map((byte) => byte.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
