package com.processpuzzle.chat.conversation.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.IdClass;
import jakarta.persistence.Index;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import java.time.Instant;
import java.util.UUID;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * One entry of a conversation's append-only log, identified by its number {@link #seq} within the
 * conversation. Messages are high-volume and written once, so they live in a plain table of their own, not
 * in the entity layer.
 *
 * <p>{@link #clientMessageId} is generated by the client, once per message: a post replayed after a lost
 * response finds the stored message instead of storing a second. It is unique per author, so one client's
 * ids cannot collide with another's.
 *
 * <p>The author is stored as the identity provider's subject plus the display name as it was at the time:
 * names cannot be looked up later without the provider's admin API, and a later rename should not rewrite
 * history. {@link #orgKey} repeats the conversation's, so erasing a tenant is one statement.
 */
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
@EqualsAndHashCode(of = {"conversationId", "seq"})
@Entity
@Table(name = "chat_message",
        uniqueConstraints = @UniqueConstraint(name = "uq_chat_message_client_id",
                columnNames = {"conversation_id", "author_sub", "client_message_id"}),
        indexes = @Index(name = "idx_chat_message_org", columnList = "org_key"))
@IdClass(MessageKey.class)
public class Message {

    @Id
    @Column(name = "conversation_id", nullable = false, updatable = false)
    private UUID conversationId;

    @Id
    @Column(nullable = false, updatable = false)
    private long seq;

    @Column(name = "org_key", nullable = false, updatable = false)
    private String orgKey;

    @Column(name = "client_message_id", nullable = false, updatable = false)
    private UUID clientMessageId;

    @Column(name = "author_sub", nullable = false, updatable = false)
    private String authorSub;

    @Column(name = "author_display_name", updatable = false)
    private String authorDisplayName;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, updatable = false)
    @Builder.Default
    private MessageKind kind = MessageKind.TEXT;

    @Column(nullable = false, length = 10000)
    private String body;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    /** Set by moderation; the row stays as an audit trail. */
    @Column(name = "deleted_at")
    private Instant deletedAt;
}
